def lst_topo_taper_beam(h1, h2, length, nelem_y):
    """
    Topology setup for a tapered beam domain consisting of
    Linear STrain (LST) triangles.

    Parameters
    ----------
    h1 : float
        Height at the beam left end (fixed end).

    h2 : float
        Height at the beam right end (free end with load).

    length : float
        Beam length.

    nelem_y : int
        Number of elements in the y-direction.

    Returns
    -------
    ElemNode : ndarray, shape (nelem, 6)
        Element connectivity. Each row contains the node numbers
        of one element. Corner nodes come first, then midside nodes.

    SysCoor : ndarray, shape (nnode, 2)
        Nodal coordinates:
        [[x1, y1],
         [x2, y2],
         ...]

    NodeSets : dict
        Useful node sets:
        - "left": nodes on left edge
        - "right": nodes on right edge
    """

    # --- Preliminary geometry calculations ---
    a = 0.4  # constant in the polynomial describing beam height
    # h(x) = a*x^2 + b*x + c
    x_hmin, hmin, x_hmax, hmax, b = quad_taper_beam_key_geom(a, length, h1, h2)

    nelem_x = round(0.5 * length / hmin * nelem_y)
    # -----------------------------------------

    # ----- Calculation of nodal coordinate matrix, SysCoor -----
    X = np.linspace(0.0, length, 2 * nelem_x + 1)  # x-coordinates for node columns
    H = a * X**2 + b * X + h1                      # beam height at node columns

    Y = np.zeros((2 * nelem_y + 1, 2 * nelem_x + 1), dtype=float)

    for colnr in range(1, nelem_x + 2):
        Y[:, 2 * colnr - 2] = np.linspace(
            H[2 * colnr - 2] / 2.0,
            -H[2 * colnr - 2] / 2.0,
            2 * nelem_y + 1
        )

    # Midside nodes on diagonals
    for colnr in range(1, nelem_x + 1):
        # Midside nodes not on diagonals in midside node columns
        for rownr in range(1, nelem_y + 2):
            Y[2 * rownr - 2, 2 * colnr - 1] = 0.5 * (
                Y[2 * rownr - 2, 2 * colnr] + Y[2 * rownr - 2, 2 * colnr - 2]
            )

        # Midside nodes on diagonals
        for rownr in range(1, nelem_y + 1):
            diag1 = (X[2 * colnr] - X[2 * colnr - 2])**2 + (
                Y[2 * rownr, 2 * colnr] - Y[2 * rownr - 2, 2 * colnr - 2]
            )**2  # downsloping diagonal

            diag2 = (X[2 * colnr] - X[2 * colnr - 2])**2 + (
                Y[2 * rownr - 2, 2 * colnr] - Y[2 * rownr, 2 * colnr - 2]
            )**2  # upsloping diagonal

            if diag1 >= diag2:
                # Upsloping diagonal is chosen
                Y[2 * rownr - 1, 2 * colnr - 1] = 0.5 * (
                    Y[2 * rownr - 2, 2 * colnr] + Y[2 * rownr, 2 * colnr - 2]
                )
            else:
                # Downsloping diagonal is chosen
                Y[2 * rownr - 1, 2 * colnr - 1] = 0.5 * (
                    Y[2 * rownr - 2, 2 * colnr - 2] + Y[2 * rownr, 2 * colnr]
                )

    nnode = (2 * nelem_x + 1) * (2 * nelem_y + 1)

    SysCoor = np.zeros((nnode, 2), dtype=float)

    for colnr in range(1, 2 * nelem_x + 2):
        start = (colnr - 1) * (2 * nelem_y + 1)
        stop = colnr * (2 * nelem_y + 1)

        SysCoor[start:stop, 1] = Y[:, colnr - 1]
        SysCoor[start:stop, 0] = X[colnr - 1]

    # ----- Element topology -----
    KeyParam = {
        "h1": h1,             # height at beam left end
        "L": length,          # beam length
        "a": a,               # constant in h(x) = a*x^2 + b*x + c
        "b": b,               # constant in h(x) = a*x^2 + b*x + c
        "nelem_y": nelem_y,   # number of elements in y-direction
        "nelem_x": nelem_x,   # number of elements in x-direction
        "X": X,               # x-coordinates for node columns
        "Y": Y                # y-coordinates for node columns
    }

    ElemNodeTemp, LeftNodes, RightNodes, FdistRight = topo_taper_lst(KeyParam)
    ElemNode = ElemNodeTemp[:, 1:]  # first column is element number in Matlab
    # -----------------------------------------

    # ----- Node sets -----
    NodeSets = {
        "left": np.asarray(LeftNodes).reshape(-1),
        "right": np.asarray(RightNodes).reshape(-1)
    }
    # ---------------------

    return ElemNode, SysCoor, NodeSets

def quad_taper_beam_key_geom(a, L, h1, h2):
    """
    Calculate minimum and maximum height locations for a beam whose height
    varies according to a quadratic polynomial:

        h(x) = a*x^2 + b*x + h1

    with beam ends at x = 0 and x = L.

    Parameters
    ----------
    a : float
        Quadratic coefficient.

    L : float
        Beam length.

    h1 : float
        Beam height at the left end, h(0) = h1.

    h2 : float
        Beam height at the right end, h(L) = h2.

    Returns
    -------
    x_hmin : float
        x-coordinate of minimum beam height.

    hmin : float
        Minimum beam height.

    x_hmax : float
        x-coordinate of maximum beam height.

    hmax : float
        Maximum beam height.

    b : float
        Linear coefficient in the beam-height polynomial.
    """
    b = -a * L + (h2 - h1) / L

    if a == 0:
        if h1 >= h2:
            x_hmax = 0.0
            hmax = h1
            x_hmin = L
            hmin = h2
        else:
            x_hmax = L
            hmax = h2
            x_hmin = 0.0
            hmin = h1

    elif a < 0:  # Beam is decreasingly quadratically tapered
        if h1 <= h2:
            hmin = h1
            x_hmin = 0.0
        else:
            hmin = h2
            x_hmin = L

        x_hmax = -b / (2 * a)
        if x_hmax < 0 or x_hmax > L:
            if h1 >= h2:
                hmax = h1
                x_hmax = 0.0
            else:
                hmax = h2
                x_hmax = L
        else:
            disk = b**2 - 4 * a * h1
            hmax = -disk / (4 * a)

    else:  # a > 0
        x_hmin = -b / (2 * a)
        if x_hmin < 0 or x_hmin > L:
            if h1 <= h2:
                hmin = h1
                x_hmin = 0.0
            else:
                hmin = h2
                x_hmin = L
        else:
            disk = b**2 - 4 * a * h1
            hmin = -disk / (4 * a)

        if h1 >= h2:
            hmax = h1
            x_hmax = 0.0
        else:
            hmax = h2
            x_hmax = L

    return x_hmin, hmin, x_hmax, hmax, b

def topo_taper_lst(key_param):
    """
    Defines the topology of a tapered beam built of LST elements.

    Parameters
    ----------
    key_param : dict
        Dictionary containing:
            h1       : height at beam left end
            L        : beam length
            a        : quadratic coefficient in h(x) = a*x^2 + b*x + c
            b        : linear coefficient in h(x) = a*x^2 + b*x + c
            nelem_y  : number of elements in y-direction
            nelem_x  : number of elements in x-direction
            X        : x-coordinates for node columns
            Y        : y-coordinates for node columns

    Returns
    -------
    ElemNode : ndarray, shape (nelem, 7)
        Element topology. First column is element number, then 6 node numbers.

    LeftNodes : ndarray
        Node numbers on the left beam end.

    RightNodes : ndarray
        Node numbers on the right beam end.

    FdistRight : ndarray
        Distribution of right-end nodal forces equivalent to a total force of 1.
    """
    h1 = key_param["h1"]
    L = key_param["L"]
    a = key_param["a"]
    b = key_param["b"]
    nelem_y = key_param["nelem_y"]
    nelem_x = key_param["nelem_x"]
    X = np.asarray(key_param["X"], dtype=float)
    Y = np.asarray(key_param["Y"], dtype=float)

    H = a * X**2 + b * X + h1  # kept for fidelity, though unused later

    node_topo = np.zeros((2 * nelem_y + 1, 2 * nelem_x + 1), dtype=int)

    for colnr in range(2 * nelem_x + 1):
        start = colnr * (2 * nelem_y + 1) + 1
        stop = (colnr + 1) * (2 * nelem_y + 1) + 1
        node_topo[:, colnr] = np.arange(start, stop)

    nelem = 2 * nelem_x * nelem_y
    ElemNode = np.zeros((nelem, 7), dtype=int)

    elemnr = 0
    for colnr in range(1, nelem_x + 1):
        for rownr in range(1, nelem_y + 1):
            diag1 = (X[2 * colnr] - X[2 * colnr - 2])**2 + (
                Y[2 * rownr, 2 * colnr] - Y[2 * rownr - 2, 2 * colnr - 2]
            )**2  # downsloping diagonal

            diag2 = (X[2 * colnr] - X[2 * colnr - 2])**2 + (
                Y[2 * rownr - 2, 2 * colnr] - Y[2 * rownr, 2 * colnr - 2]
            )**2  # upsloping diagonal

            if diag1 >= diag2:  # upsloping diagonal is chosen
                # Upper element
                ElemNode[elemnr, 0] = elemnr + 1
                ElemNode[elemnr, 1] = node_topo[2 * rownr,     2 * colnr - 2]  # lower left
                ElemNode[elemnr, 2] = node_topo[2 * rownr - 2, 2 * colnr]      # upper right
                ElemNode[elemnr, 3] = node_topo[2 * rownr - 2, 2 * colnr - 2]  # upper left
                ElemNode[elemnr, 4] = node_topo[2 * rownr - 1, 2 * colnr - 1]  # lower midside
                ElemNode[elemnr, 5] = node_topo[2 * rownr - 2, 2 * colnr - 1]  # upper midside
                ElemNode[elemnr, 6] = node_topo[2 * rownr - 1, 2 * colnr - 2]  # left midside

                # Lower element
                elemnr += 1
                ElemNode[elemnr, 0] = elemnr + 1
                ElemNode[elemnr, 1] = node_topo[2 * rownr,     2 * colnr - 2]  # lower left
                ElemNode[elemnr, 2] = node_topo[2 * rownr,     2 * colnr]      # lower right
                ElemNode[elemnr, 3] = node_topo[2 * rownr - 2, 2 * colnr]      # upper left
                ElemNode[elemnr, 4] = node_topo[2 * rownr,     2 * colnr - 1]  # lower midside
                ElemNode[elemnr, 5] = node_topo[2 * rownr - 1, 2 * colnr]      # right midside
                ElemNode[elemnr, 6] = node_topo[2 * rownr - 1, 2 * colnr - 1]  # upper midside

                elemnr += 1

            else:  # downsloping diagonal is chosen
                # Upper element
                ElemNode[elemnr, 0] = elemnr + 1
                ElemNode[elemnr, 1] = node_topo[2 * rownr - 2, 2 * colnr - 2]  # upper left
                ElemNode[elemnr, 2] = node_topo[2 * rownr,     2 * colnr]      # lower right
                ElemNode[elemnr, 3] = node_topo[2 * rownr - 2, 2 * colnr]      # upper right
                ElemNode[elemnr, 4] = node_topo[2 * rownr - 1, 2 * colnr - 1]  # lower midside
                ElemNode[elemnr, 5] = node_topo[2 * rownr - 1, 2 * colnr]      # right midside
                ElemNode[elemnr, 6] = node_topo[2 * rownr - 2, 2 * colnr - 1]  # upper midside

                # Lower element
                elemnr += 1
                ElemNode[elemnr, 0] = elemnr + 1
                ElemNode[elemnr, 1] = node_topo[2 * rownr,     2 * colnr - 2]  # lower left
                ElemNode[elemnr, 2] = node_topo[2 * rownr,     2 * colnr]      # lower right
                ElemNode[elemnr, 3] = node_topo[2 * rownr - 2, 2 * colnr - 2]  # upper left
                ElemNode[elemnr, 4] = node_topo[2 * rownr,     2 * colnr - 1]  # lower midside
                ElemNode[elemnr, 5] = node_topo[2 * rownr - 1, 2 * colnr - 1]  # upper midside
                ElemNode[elemnr, 6] = node_topo[2 * rownr - 1, 2 * colnr - 2]  # left midside

                elemnr += 1

    # Boundary node outputs
    rev_idx = np.arange(2 * nelem_y, -1, -1)
    LeftNodes = node_topo[rev_idx, 0]
    RightNodes = node_topo[rev_idx, 2 * nelem_x]

    # Distribution of right-end node forces equivalent to total applied force = 1
    FdistRight = np.zeros((2 * nelem_y + 1, 1), dtype=float)
    Felem = np.array([[1 / 6], [2 / 3], [1 / 6]], dtype=float) / nelem_y
    for i in range(nelem_y):
        FdistRight[2 * i:2 * i + 3, 0:1] += Felem

    return ElemNode, LeftNodes, RightNodes, FdistRight

def solveq(K, f, bc=None):
    """
    Solve static FE equations with optional boundary conditions.

    Parameters
    ----------
    K : array_like, shape (nd, nd)
        Global stiffness matrix.

    f : array_like, shape (nd,) or (nd, 1)
        Global load vector.

    bc : array_like, shape (nbc, 2), optional
        Boundary condition matrix:
        bc[:, 0] -> prescribed dof numbers
        bc[:, 1] -> prescribed values

        Note:
        If bc comes directly from MATLAB-style code, dof numbering is
        1-based. This function converts it to Python's 0-based indexing.

    Returns
    -------
    d : ndarray, shape (nd,)
        Solution vector including prescribed boundary values.

    Q : ndarray, shape (nd,)
        Reaction force vector.
    """
    K = np.asarray(K, dtype=float)
    f = np.asarray(f, dtype=float).reshape(-1)

    if bc is None:
        d = np.linalg.solve(K, f)
        Q = K @ d - f
        return d, Q

    bc = np.asarray(bc, dtype=float)

    nd = K.shape[0]
    fdof = np.arange(nd, dtype=int)

    d = np.zeros(nd, dtype=float)
    Q = np.zeros(nd, dtype=float)

    # MATLAB -> Python index conversion
    pdof = bc[:, 0].astype(int) - 1
    dp = bc[:, 1]

    fdof = np.setdiff1d(fdof, pdof)

    s = np.linalg.solve(
        K[np.ix_(fdof, fdof)],
        f[fdof] - K[np.ix_(fdof, pdof)] @ dp
    )

    d[pdof] = dp
    d[fdof] = s

    Q = K @ d - f
    return d, Q

def von_mises_dep(Sigma, D, yield_value, s_type):
    """
    Calculate the von Mises stress and the elasto-plastic constitutive matrix.

    Parameters
    ----------
    Sigma : array_like, shape (nsigma,)
        Stress vector.

        Plane stress:
            [sigx, sigy, tauxy]

        Plane strain:
            [sigx, sigy, sigz, tauxy]

    D : array_like, shape (nsigma, nsigma)
        Elastic constitutive matrix.

    yield_value : float
        von Mises yield stress.

    s_type : int
        Stress type:
            1 -> plane stress
            2 -> plane strain

    Returns
    -------
    sigMises : float
        von Mises equivalent stress.

    Dep : ndarray
        Elasto-plastic constitutive matrix.
    """
    Sigma = np.asarray(Sigma, dtype=float).reshape(-1)
    D = np.asarray(D, dtype=float)

    # ----- Plane stress ----------------------------------------------
    if s_type == 1:
        sigx = Sigma[0]
        sigy = Sigma[1]
        tau = Sigma[2]

        sigMises = np.sqrt(sigx**2 + sigy**2 - sigx * sigy + 3 * tau**2)

        if sigMises > 0:
            A = (1.0 / (2.0 * sigMises)) * np.array([
                2.0 * sigx - sigy,
                2.0 * sigy - sigx,
                6.0 * tau
            ])
        else:
            A = np.zeros(3)

    # ----- Plane strain ----------------------------------------------
    elif s_type == 2:
        sigx = Sigma[0]
        sigy = Sigma[1]
        sigz = Sigma[2]
        tau = Sigma[3]

        sigMises = np.sqrt(
            (sigx - sigy)**2 +
            (sigy - sigz)**2 +
            (sigz - sigx)**2 +
            3.0 * tau**2
        )

        if sigMises > 0:
            A = (1.0 / (2.0 * sigMises)) * np.array([
                2.0 * sigx - sigy - sigz,
                -sigx + 2.0 * sigy - sigz,
                -sigx - sigy + 2.0 * sigz,
                6.0 * tau
            ])
        else:
            A = np.zeros(4)

    else:
        raise ValueError("s_type must be 1 (plane stress) or 2 (plane strain)")

    # --- Criterion check and constitutive matrix ----
    f = sigMises - yield_value

    if f >= 0 and sigMises > 0:
        denom = A @ D @ A
        if abs(denom) > 0:
            Dep = D - np.outer(D @ A, D @ A) / denom
        else:
            Dep = D.copy()
    else:
        Dep = D.copy()

    return sigMises, Dep

