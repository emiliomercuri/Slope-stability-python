def b_lst(elem_coord, acoor, s_type):
    """
    Calculate the strain-distribution matrix B for a 6-noded LST triangle.

    Parameters
    ----------
    elem_coord : array_like, shape (6, 2)
        Nodal coordinates:
        [[x1, y1],
         [x2, y2],
         [x3, y3],
         [x4, y4],
         [x5, y5],
         [x6, y6]]

    acoor : array_like, shape (3,)
        Area (natural) coordinates of the evaluation point:
        [xi1, xi2, xi3]

    s_type : int
        Stress type:
        1 -> plane stress  (nsigma = 3)
        2 -> plane strain  (nsigma = 4)
        3 -> axisymmetry   (not implemented)

    Returns
    -------
    B : ndarray
        Strain-distribution matrix of shape (nsigma, 12).

    Notes
    -----
    This function is a faithful translation of the original Matlab code.
    For s_type == 2, the 3rd row remains zero and the 4th row stores the
    shear-strain terms, exactly as in the Matlab routine.
    """
    elem_coord = np.asarray(elem_coord, dtype=float)
    acoor = np.asarray(acoor, dtype=float)

    if s_type == 1:  # Plane stress
        nsigma = 3
    elif s_type == 2:  # Plane strain
        nsigma = 4
    else:
        raise NotImplementedError("s_type = 3 (axisymmetry) is not implemented.")

    # ----- Coordinate variables and element area --------------------
    x13 = elem_coord[0, 0] - elem_coord[2, 0]
    x21 = elem_coord[1, 0] - elem_coord[0, 0]
    x32 = elem_coord[2, 0] - elem_coord[1, 0]

    y12 = elem_coord[0, 1] - elem_coord[1, 1]
    y23 = elem_coord[1, 1] - elem_coord[2, 1]
    y31 = elem_coord[2, 1] - elem_coord[0, 1]

    A = 0.5 * (x21 * y31 - x13 * y12)

    # ----- Extraction of natural coordinates ------------------------
    xi1, xi2, xi3 = acoor

    # ----- Strain distribution matrix -------------------------------
    B = np.zeros((nsigma, 12), dtype=float)

    B[0, 0]  = (4 * xi1 - 1) * y23
    B[nsigma - 1, 1] = B[0, 0]

    B[0, 2]  = (4 * xi2 - 1) * y31
    B[nsigma - 1, 3] = B[0, 2]

    B[0, 4]  = (4 * xi3 - 1) * y12
    B[nsigma - 1, 5] = B[0, 4]

    B[0, 6]  = 4 * xi2 * y23 + 4 * xi1 * y31
    B[nsigma - 1, 7] = B[0, 6]

    B[0, 8]  = 4 * xi3 * y31 + 4 * xi2 * y12
    B[nsigma - 1, 9] = B[0, 8]

    B[0, 10] = 4 * xi3 * y23 + 4 * xi1 * y12
    B[nsigma - 1, 11] = B[0, 10]

    B[1, 1]  = (4 * xi1 - 1) * x32
    B[nsigma - 1, 0] = B[1, 1]

    B[1, 3]  = (4 * xi2 - 1) * x13
    B[nsigma - 1, 2] = B[1, 3]

    B[1, 5]  = (4 * xi3 - 1) * x21
    B[nsigma - 1, 4] = B[1, 5]

    B[1, 7]  = 4 * xi2 * x32 + 4 * xi1 * x13
    B[nsigma - 1, 6] = B[1, 7]

    B[1, 9]  = 4 * xi3 * x13 + 4 * xi2 * x21
    B[nsigma - 1, 8] = B[1, 9]

    B[1, 11] = 4 * xi3 * x32 + 4 * xi1 * x21
    B[nsigma - 1, 10] = B[1, 11]

    B = B / (2 * A)

    return B

def elem_disp_draw_2d(elem_x, elem_y, elem_disp, plotpar, nspline, mfac):
    """
    Draw deformed 2D finite elements of the same type.

    Parameters
    ----------
    elem_x : array_like, shape (nelem, nnode_elem)
        Element x-coordinates.

    elem_y : array_like, shape (nelem, nnode_elem)
        Element y-coordinates.

    elem_disp : array_like, shape (nelem, ndof_elem)
        Element displacements.

    plotpar : str
        Plot style string, similar to MATLAB, e.g. '-rx'.
        The first two characters are used for the deformed element lines.
        If length is 3, the third character is used to plot nodes.

    nspline : int
        Number of points to draw along each element side.

    mfac : float
        Displacement magnification factor.

    Returns
    -------
    magnfac : float
        Returns the same magnification factor `mfac`, matching MATLAB usage.
    """
    elem_x = np.asarray(elem_x, dtype=float)
    elem_y = np.asarray(elem_y, dtype=float)
    elem_disp = np.asarray(elem_disp, dtype=float)

    a = elem_x.shape
    b = elem_y.shape

    if a == b:
        nelem = a[0]
        nnode_elem = a[1]
    else:
        raise ValueError("Coordinate matrices have incompatible sizes")

    c = elem_disp.shape
    if c[0] != a[0]:
        raise ValueError("ElemDisp has incorrect size")

    nanvek = np.nan * np.ones((nelem, 1))

    # ----- Triangular elements -----------------------------------------
    if nnode_elem == 3:  # CST elements
        X = np.column_stack([elem_x[:, 0], elem_x[:, 1], elem_x[:, 2], elem_x[:, 0]])
        Y = np.column_stack([elem_y[:, 0], elem_y[:, 1], elem_y[:, 2], elem_y[:, 0]])

        Xs = np.hstack([X + mfac * elem_disp[:, [0, 2, 4, 0]], nanvek]).T
        Ys = np.hstack([Y + mfac * elem_disp[:, [1, 3, 5, 1]], nanvek]).T

    elif nnode_elem == 6:  # LST elements
        X = np.column_stack([
            elem_x[:, 0], elem_x[:, 3], elem_x[:, 1],
            elem_x[:, 4], elem_x[:, 2], elem_x[:, 5], elem_x[:, 0]
        ])
        Y = np.column_stack([
            elem_y[:, 0], elem_y[:, 3], elem_y[:, 1],
            elem_y[:, 4], elem_y[:, 2], elem_y[:, 5], elem_y[:, 0]
        ])

        Xdisp = X + mfac * elem_disp[:, [0, 6, 2, 8, 4, 10, 0]]
        Ydisp = Y + mfac * elem_disp[:, [1, 7, 3, 9, 5, 11, 1]]

        xiop = np.linspace(0, 1, nspline)
        xined = np.linspace(1, 0, nspline)

        # Side 1
        N1s1 = xined * (2 * xined - 1)
        N2s1 = xiop * (2 * xiop - 1)
        N4s1 = 4 * xiop * xined

        # Side 2
        N2s2 = xined * (2 * xined - 1)
        N3s2 = xiop * (2 * xiop - 1)
        N5s2 = 4 * xiop * xined

        # Side 3
        N3s3 = xined * (2 * xined - 1)
        N1s3 = xiop * (2 * xiop - 1)
        N6s3 = 4 * xiop * xined

        Xs = np.vstack([
            np.column_stack([Xdisp[:, 0:1] * N1s1 + Xdisp[:, 1:2] * N4s1 + Xdisp[:, 2:3] * N2s1, nanvek]),
            np.column_stack([Xdisp[:, 2:3] * N2s2 + Xdisp[:, 3:4] * N5s2 + Xdisp[:, 4:5] * N3s2, nanvek]),
            np.column_stack([Xdisp[:, 4:5] * N3s3 + Xdisp[:, 5:6] * N6s3 + Xdisp[:, 6:7] * N1s3, nanvek]),
        ]).T

        Ys = np.vstack([
            np.column_stack([Ydisp[:, 0:1] * N1s1 + Ydisp[:, 1:2] * N4s1 + Ydisp[:, 2:3] * N2s1, nanvek]),
            np.column_stack([Ydisp[:, 2:3] * N2s2 + Ydisp[:, 3:4] * N5s2 + Ydisp[:, 4:5] * N3s2, nanvek]),
            np.column_stack([Ydisp[:, 4:5] * N3s3 + Ydisp[:, 5:6] * N6s3 + Ydisp[:, 6:7] * N1s3, nanvek]),
        ]).T

    elif nnode_elem == 10:  # QST elements
        X = np.column_stack([
            elem_x[:, 0], elem_x[:, 3], elem_x[:, 4], elem_x[:, 1],
            elem_x[:, 5], elem_x[:, 6], elem_x[:, 2], elem_x[:, 7],
            elem_x[:, 8], elem_x[:, 0]
        ])
        Y = np.column_stack([
            elem_y[:, 0], elem_y[:, 3], elem_y[:, 4], elem_y[:, 1],
            elem_y[:, 5], elem_y[:, 6], elem_y[:, 2], elem_y[:, 7],
            elem_y[:, 8], elem_y[:, 0]
        ])

        Xdisp = X + mfac * elem_disp[:, [0, 6, 8, 2, 10, 12, 4, 14, 16, 0]]
        Ydisp = Y + mfac * elem_disp[:, [1, 7, 9, 3, 11, 13, 5, 15, 17, 1]]

        print("Note: ElemDispDraw2D has not yet been tested for QST elements")

        xiop = np.linspace(0, 1, nspline)
        xined = np.linspace(1, 0, nspline)

        # Side 1
        N1s1 = 0.5 * xined * (3 * xined - 1) * (3 * xined - 2)
        N2s1 = 0.5 * xiop * (3 * xiop - 1) * (3 * xiop - 2)
        N4s1 = 4.5 * xiop * xined * (3 * xined - 1)
        N5s1 = 4.5 * xined * xiop * (3 * xiop - 1)

        # Side 2
        N2s2 = N1s1
        N3s2 = N2s1
        N6s2 = N4s1
        N7s2 = N5s1

        # Side 3
        N3s3 = N2s2
        N1s3 = N3s2
        N8s3 = N6s2
        N9s3 = N7s2

        Xs = np.vstack([
            np.column_stack([Xdisp[:, 0:1] * N1s1 + Xdisp[:, 1:2] * N4s1 + Xdisp[:, 2:3] * N5s1 + Xdisp[:, 3:4] * N2s1, nanvek]),
            np.column_stack([Xdisp[:, 3:4] * N2s2 + Xdisp[:, 4:5] * N6s2 + Xdisp[:, 5:6] * N7s2 + Xdisp[:, 6:7] * N3s2, nanvek]),
            np.column_stack([Xdisp[:, 6:7] * N3s3 + Xdisp[:, 7:8] * N8s3 + Xdisp[:, 8:9] * N9s3 + Xdisp[:, 9:10] * N1s3, nanvek]),
        ]).T

        Ys = np.vstack([
            np.column_stack([Ydisp[:, 0:1] * N1s1 + Ydisp[:, 1:2] * N4s1 + Ydisp[:, 2:3] * N5s1 + Ydisp[:, 3:4] * N2s1, nanvek]),
            np.column_stack([Ydisp[:, 3:4] * N2s2 + Ydisp[:, 4:5] * N6s2 + Ydisp[:, 5:6] * N7s2 + Ydisp[:, 6:7] * N3s2, nanvek]),
            np.column_stack([Ydisp[:, 6:7] * N3s3 + Ydisp[:, 7:8] * N8s3 + Ydisp[:, 8:9] * N9s3 + Ydisp[:, 9:10] * N1s3, nanvek]),
        ]).T

    # ----- Quadrilateral elements ------------------------------------
    elif nnode_elem == 4:
        X = np.column_stack([elem_x[:, 0], elem_x[:, 1], elem_x[:, 2], elem_x[:, 3], elem_x[:, 0]])
        Y = np.column_stack([elem_y[:, 0], elem_y[:, 1], elem_y[:, 2], elem_y[:, 3], elem_y[:, 0]])

        Xs = np.hstack([X + mfac * elem_disp[:, [0, 2, 4, 6, 0]], nanvek]).T
        Ys = np.hstack([Y + mfac * elem_disp[:, [1, 3, 5, 7, 1]], nanvek]).T

    elif nnode_elem == 8:  # serendipity element
        X = np.column_stack([
            elem_x[:, 0], elem_x[:, 4], elem_x[:, 1], elem_x[:, 5],
            elem_x[:, 2], elem_x[:, 6], elem_x[:, 3], elem_x[:, 7], elem_x[:, 0]
        ])
        Y = np.column_stack([
            elem_y[:, 0], elem_y[:, 4], elem_y[:, 1], elem_y[:, 5],
            elem_y[:, 2], elem_y[:, 6], elem_y[:, 3], elem_y[:, 7], elem_y[:, 0]
        ])

        Xdisp = X + mfac * elem_disp[:, [0, 8, 2, 10, 4, 12, 6, 14, 0]]
        Ydisp = Y + mfac * elem_disp[:, [1, 9, 3, 11, 5, 13, 7, 15, 1]]

        xiop = np.linspace(-1, 1, nspline)
        xined = np.linspace(1, -1, nspline)

        # Side 1
        N5s1 = (1 - xiop**2)
        N1s1 = 0.5 * (1 - xiop) - 0.5 * N5s1
        N2s1 = 0.5 * (1 + xiop) - 0.5 * N5s1

        # Side 2
        N6s2 = (1 - xiop**2)
        N2s2 = 0.5 * (1 - xiop) - 0.5 * N6s2
        N3s2 = 0.5 * (1 + xiop) - 0.5 * N6s2

        # Side 3
        N7s3 = (1 - xined**2)
        N3s3 = 0.5 * (1 + xined) - 0.5 * N7s3
        N4s3 = 0.5 * (1 - xined) - 0.5 * N7s3

        # Side 4
        N8s4 = (1 - xined**2)
        N4s4 = 0.5 * (1 + xined) - 0.5 * N8s4
        N1s4 = 0.5 * (1 - xined) - 0.5 * N8s4

        Xs = np.vstack([
            np.column_stack([Xdisp[:, 0:1] * N1s1 + Xdisp[:, 1:2] * N5s1 + Xdisp[:, 2:3] * N2s1, nanvek]),
            np.column_stack([Xdisp[:, 2:3] * N2s2 + Xdisp[:, 3:4] * N6s2 + Xdisp[:, 4:5] * N3s2, nanvek]),
            np.column_stack([Xdisp[:, 4:5] * N3s3 + Xdisp[:, 5:6] * N7s3 + Xdisp[:, 6:7] * N4s3, nanvek]),
            np.column_stack([Xdisp[:, 6:7] * N4s4 + Xdisp[:, 7:8] * N8s4 + Xdisp[:, 8:9] * N1s4, nanvek]),
        ]).T

        Ys = np.vstack([
            np.column_stack([Ydisp[:, 0:1] * N1s1 + Ydisp[:, 1:2] * N5s1 + Ydisp[:, 2:3] * N2s1, nanvek]),
            np.column_stack([Ydisp[:, 2:3] * N2s2 + Ydisp[:, 3:4] * N6s2 + Ydisp[:, 4:5] * N3s2, nanvek]),
            np.column_stack([Ydisp[:, 4:5] * N3s3 + Ydisp[:, 5:6] * N7s3 + Ydisp[:, 6:7] * N4s3, nanvek]),
            np.column_stack([Ydisp[:, 6:7] * N4s4 + Ydisp[:, 7:8] * N8s4 + Ydisp[:, 8:9] * N1s4, nanvek]),
        ]).T

    else:
        raise ValueError("Sorry, this element is currently not supported!")

    Xk = X.T
    Yk = Y.T
    xknude = Xk.reshape(-1, order='F')
    yknude = Yk.reshape(-1, order='F')

    # ----- Plotting ---------------------------------------------------
    plt.axis('equal')

    line_style = plotpar[:2] if len(plotpar) >= 2 else plotpar
    plt.plot(Xs.reshape(-1, order='F'), Ys.reshape(-1, order='F'), line_style)

    if len(plotpar) == 3:
        plt.plot(xknude, yknude, plotpar[2])

    return mfac

